#!/usr/bin/env python3
"""Builds supabase/rollback/slice4a_rollback.sql: removes slice 4a and restores the exact definitions in force before it,
extracted (not retyped) from the migration files committed at HEAD: premier_recon_trueup / premier_lock_payday /
premier_recon_hub_open from PR #7's 20261101120000 (which lands first), recon_line_pays / payroll_cutoffs_guard from
slice three's 20261031210100 / 20261031210200."""
import re, subprocess, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
def show(path):
    return subprocess.run(['git', '-C', str(root), 'show', f'HEAD:{path}'], check=True, capture_output=True, text=True).stdout
v = show('supabase/migrations/20261031210100_premier_recon_views.sql')
r = show('supabase/migrations/20261031210200_premier_recon_rls_events.sql')
h = show('supabase/migrations/20261101120000_hub_lock_open_items.sql')
def fn(src, name):
    m = re.search(r'^create or replace function public\.' + re.escape(name) + r'\(.*?^(?:end )?\$\$;\n', src, re.S | re.M)
    assert m, name
    return m.group(0)
def view(src, name, end='where public.recon_can_read();'):
    m = re.search(r'^create or replace view public\.' + re.escape(name) + r' .*?;\n', src, re.S | re.M)
    assert m and m.group(0).rstrip().endswith(end), name
    return m.group(0)
blocks = [fn(v, 'recon_line_pays'), fn(r, 'payroll_cutoffs_guard'), fn(h, 'premier_lock_payday'), view(h, 'premier_recon_trueup')]
hub_open = view(h, 'premier_recon_hub_open', 'where o.paid_on is null and public.recon_can_read();')
out = root / 'supabase/rollback/slice4a_rollback.sql'
out.write_text("""-- Slice 4a ROLLBACK (actuals ledger + closed-week next-open-payday). ONE transaction. Paste into the SQL Editor only
-- with the Orchestrator's go-ahead. Generated by scripts/build_slice4a_rollback.py from the committed migration files:
-- the replaced objects are restored byte-for-byte from PR #7's 20261101120000 (true-up, lock, premier_recon_hub_open) and
-- slice three's 20261031210100 / 20261031210200 (recon_line_pays, payroll_cutoffs_guard). PR #7 stays applied.
-- REFUSES (no change) when: closed-week autopay is ON (closed_week_policy <> 'hold'; switch it off first with
-- slice4a_autopay_off.sql), or any closed-week carry anchor exists (those are payroll records). The ledger itself is DERIVED from source rows that stay (manual /
-- overhead entries, locks, adjustments, hub paid lock): dropping it loses nothing; re-applying 4a re-posts it.
begin;
do $$
declare pol text; anc int; tx int;
begin
  if to_regclass('public.ledger_accounts') is null and to_regclass('public.closed_week_carry_anchors') is null then
    raise notice 'rollback: slice 4a not present; nothing to do'; return;
  end if;
  select closed_week_policy into pol from public.recon_pay_config where id;
  if pol is distinct from 'hold' then
    raise exception 'slice-4a rollback refused: closed-week autopay is ON (policy=%); run slice4a_autopay_off.sql first (Kyle decides)', pol;
  end if;
  select count(*) into anc from public.closed_week_carry_anchors;
  if anc > 0 then raise exception 'slice-4a rollback refused: % closed-week carry anchor(s) exist (payroll records); export first', anc; end if;
  select count(*) into tx from public.ledger_transactions;
  raise notice 'rollback: dropping the ledger (% derived transaction(s)) and the closed-week carry', tx;
end $$;

-- ledger: source triggers first, then views, functions, tables
do $$ declare t text; begin
  foreach t in array array['manual_entries', 'overhead_entries', 'pay_line_locks', 'pay_adjustments', 'hub_paid_lock', 'hub_cutover', 'payroll_cutoffs'] loop
    execute format('drop trigger if exists ledger_post_%I on public.%I', t, t);
  end loop;
end $$;
drop view if exists public.pl_projected_vs_actual_weekly, public.pl_projected_monthly, public.pl_projected_weekly, public.pl_projected_daily,
  public.pl_actual_monthly, public.pl_actual_weekly, public.pl_actual_overhead_weekly, public.pl_actual_daily, public.pl_actual_lines,
  public.ledger_health, public.ledger_trial_balance, public.ledger_unposted_sources, public.ledger_pending_sources;
drop function if exists public.ledger_check(), public.ledger_sync(), public.ledger_post_trigger(), public.ledger_post_pending(),
  public.ledger_manual_account(text, text), public.ledger_post_pair(date, text, bigint, text, text, text, numeric, text, text, text);
drop table if exists public.ledger_lines, public.ledger_transactions, public.ledger_accounts, public.ledger_watermarks;
drop function if exists public.ledger_entry_date(text, text, date), public.ledger_can_read();
drop function if exists public.ledger_balance_check(), public.ledger_immutable();

-- closed week: restore #7's true-up (4a appended 5 columns, so drop + create; premier_recon_hub_open depends on it and is
-- re-created from #7's file) and the functions, then drop the 4a objects
drop view if exists public.premier_recon_hub_open;
drop view if exists public.premier_recon_trueup;
""" + '\n'.join(blocks) + """
revoke all on public.premier_recon_trueup from public, anon, authenticated;
grant select on public.premier_recon_trueup to authenticated;
""" + hub_open + """revoke all on public.premier_recon_hub_open from public, anon, authenticated;
grant select on public.premier_recon_hub_open to authenticated;
drop trigger if exists pay_adjustments_after_cutover on public.pay_adjustments;
drop function if exists public.pay_adjustment_after_cutover(), public.recon_hub_era_late(text, timestamptz);
drop function if exists public.recon_anchor_closed_week_carry(), public.recon_next_open_payday(date);
drop table if exists public.closed_week_carry_anchors;
alter table public.recon_pay_config drop column if exists closed_week_policy;
delete from supabase_migrations.schema_migrations where version in ('20261101130000', '20261101130100');
commit;
notify pgrst, 'reload schema';
""")
print(out)
