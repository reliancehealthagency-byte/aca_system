#!/usr/bin/env python3
"""Builds supabase/rollback/slice4a_rollback.sql: removes slice 4a and restores the exact slice-three definitions of the
objects 20261101100100 replaced, extracted from the slice-three migration files on origin/main (not retyped)."""
import re, subprocess, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
def show(path):
    return subprocess.run(['git', '-C', str(root), 'show', f'origin/main:{path}'], check=True, capture_output=True, text=True).stdout
v = show('supabase/migrations/20261031210100_premier_recon_views.sql')
r = show('supabase/migrations/20261031210200_premier_recon_rls_events.sql')
def fn(src, name):
    m = re.search(r'^create or replace function public\.' + re.escape(name) + r'\(.*?^(?:end )?\$\$;\n', src, re.S | re.M)
    assert m, name
    return m.group(0)
def view(src, name):
    m = re.search(r'^create or replace view public\.' + re.escape(name) + r' .*?;\n', src, re.S | re.M)
    assert m and m.group(0).rstrip().endswith('where public.recon_can_read();'), name
    return m.group(0)
blocks = [fn(v, 'recon_line_pays'), fn(r, 'payroll_cutoffs_guard'), fn(r, 'premier_lock_payday'), view(v, 'premier_recon_trueup')]
out = root / 'supabase/rollback/slice4a_rollback.sql'
out.write_text("""-- Slice 4a ROLLBACK (actuals ledger + closed-week next-open-payday). ONE transaction. Paste into the SQL Editor only
-- with the Orchestrator's go-ahead. Generated by scripts/build_slice4a_rollback.py from origin/main's slice-three files:
-- the four replaced objects are restored byte-for-byte from 20261031210100 / 20261031210200.
-- REFUSES (no change) when: autopay is ON (20261101100200 recorded or closed_week_policy <> 'hold'), or any closed-week
-- carry anchor exists (those are payroll records). The ledger itself is DERIVED from source rows that stay (manual /
-- overhead entries, locks, adjustments, hub paid lock): dropping it loses nothing; re-applying 4a re-posts it.
begin;
do $$
declare on3 int; pol text; anc int; tx int;
begin
  if to_regclass('public.ledger_accounts') is null and to_regclass('public.closed_week_carry_anchors') is null then
    raise notice 'rollback: slice 4a not present; nothing to do'; return;
  end if;
  select count(*) into on3 from supabase_migrations.schema_migrations where version = '20261101100200';
  select closed_week_policy into pol from public.recon_pay_config where id;
  if on3 > 0 or pol is distinct from 'hold' then
    raise exception 'slice-4a rollback refused: closed-week autopay is ON (100200 recorded=%, policy=%); Kyle decides before it is turned off', on3, pol;
  end if;
  select count(*) into anc from public.closed_week_carry_anchors;
  if anc > 0 then raise exception 'slice-4a rollback refused: % closed-week carry anchor(s) exist (payroll records); export first', anc; end if;
  select count(*) into tx from public.ledger_transactions;
  raise notice 'rollback: dropping the ledger (% derived transaction(s)) and the closed-week carry', tx;
end $$;

-- ledger: source triggers first, then views, functions, tables
do $$ declare t text; begin
  foreach t in array array['manual_entries', 'overhead_entries', 'pay_line_locks', 'pay_adjustments', 'hub_paid_lock', 'hub_cutover', 'payroll_cutoffs'] loop
    execute format('drop trigger if exists ledger_post_%I on public.%I', t, t);
  end loop;
end $$;
drop view if exists public.pl_projected_vs_actual_weekly, public.pl_projected_monthly, public.pl_projected_weekly, public.pl_projected_daily,
  public.pl_actual_monthly, public.pl_actual_weekly, public.pl_actual_overhead_weekly, public.pl_actual_daily, public.pl_actual_lines,
  public.ledger_health, public.ledger_trial_balance, public.ledger_unposted_sources, public.ledger_pending_sources;
drop function if exists public.ledger_sync(), public.ledger_post_trigger(), public.ledger_post_pending(),
  public.ledger_manual_account(text, text), public.ledger_post_pair(date, text, bigint, text, text, text, numeric, text, text, text);
drop table if exists public.ledger_lines, public.ledger_transactions, public.ledger_accounts;
drop function if exists public.ledger_balance_check(), public.ledger_immutable();

-- closed week: restore slice three's view (it has 4 fewer columns, so drop + create) and functions, then drop 4a objects
drop view if exists public.premier_recon_trueup;
""" + '\n'.join(blocks) + """
revoke all on public.premier_recon_trueup from public, anon, authenticated;
grant select on public.premier_recon_trueup to authenticated;
drop function if exists public.recon_anchor_closed_week_carry(), public.recon_next_open_payday(date);
drop table if exists public.closed_week_carry_anchors;
alter table public.recon_pay_config drop column if exists closed_week_policy;
delete from supabase_migrations.schema_migrations where version in ('20261101100000', '20261101100100');
commit;
notify pgrst, 'reload schema';
""")
print(out)
