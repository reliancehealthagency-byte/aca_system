#!/usr/bin/env python3
"""Builds supabase/rollback/agent_attribution_rollback.sql: removes 20261101090000 and restores slice three's
recon_agent_id and board_parse_raw byte-for-byte from origin/main's 20261031210000 (not retyped)."""
import re, subprocess, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = subprocess.run(['git', '-C', str(root), 'show', 'origin/main:supabase/migrations/20261031210000_premier_recon_tables.sql'],
                     check=True, capture_output=True, text=True).stdout
def fn(name, ender):
    m = re.search(r'^create or replace function public\.' + re.escape(name) + r'\(.*?' + ender, src, re.S | re.M)
    assert m, name
    return m.group(0)
blocks = [fn('recon_agent_id', r"\$\$;\n"), fn('board_parse_raw', r"^end \$\$;\n")]
out = root / 'supabase/rollback/agent_attribution_rollback.sql'
out.write_text("""-- Agent attribution (20261101090000) ROLLBACK. ONE transaction; SQL Editor, Orchestrator go-ahead only.
-- Generated by scripts/build_agent_attribution_rollback.py: recon_agent_id and board_parse_raw are restored byte-for-byte
-- from origin/main's 20261031210000. REFUSES (no change) if any board row was imported under the new rules with a typed
-- spelling different from its stored agent_name (dropping agent_name_typed would lose it): export those first.
-- Alias rows stay (they are owner data); the kind column is dropped.
begin;
do $$
declare n int;
begin
  if to_regclass('public.board_unknown_agents') is null then raise notice 'rollback: agent attribution not present; nothing to do'; return; end if;
  select count(*) into n from public.board_submissions where agent_name_typed is distinct from agent_name and agent_name_typed is not null;
  if n > 0 then raise exception 'agent-attribution rollback refused: % board row(s) store a standard name different from the typed one', n; end if;
end $$;
drop view if exists public.board_unknown_agents;
""" + '\n'.join(blocks) + """
alter table public.board_submissions drop column if exists agent_name_typed;
alter table public.agent_name_aliases drop constraint if exists agent_name_aliases_kind;
alter table public.agent_name_aliases drop column if exists kind;
drop function if exists public.recon_name_key(text);
delete from supabase_migrations.schema_migrations where version = '20261101090000';
commit;
notify pgrst, 'reload schema';
""")
print(out)
